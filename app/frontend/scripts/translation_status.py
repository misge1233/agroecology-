#!/usr/bin/env python3
"""Regenerate docs/i18n/TRANSLATION_STATUS.md from the catalogs (U1).

Lists every translatable key — the next-intl messages, the glossary tables in
src/i18n/glossary.ts and the backend catalogs in app/backend/app/i18n — with its
review status. Rows default to ``machine-draft``; the owner flips reviewed rows
by editing REVIEWED below (key → "reviewed") and re-running the script, so the
document stays reproducible instead of hand-edited.

Run from the repo root or app/frontend:  python scripts/translation_status.py
"""
from __future__ import annotations

import json
import re
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve()
ROOT = HERE.parents[3]          # repo root
FRONTEND = ROOT / "app" / "frontend"
OUT = ROOT / "docs" / "i18n" / "TRANSLATION_STATUS.md"

# Keys a native speaker has signed off (per language). Edit and re-run.
REVIEWED: dict[str, set[str]] = {"am": set(), "om": set()}

GLOSSARY_TABLES = (
    "FAMILIES", "FAMILIES_SHORT", "FAMILIES_BLURB", "INDICATORS", "INDICATOR_NOUNS",
    "AEZ_BELTS", "CROP_GROUPS", "CONFIDENCE", "CONFIDENCE_MEANING", "TIERS",
    "SOURCE_MODES", "SOURCE_MODES_TOOLTIP", "COMPONENTS",
)


def flatten(d: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for k, v in d.items():
        key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            out.update(flatten(v, key))
        else:
            out[key] = v
    return out


def main() -> int:
    rows: list[tuple[str, str, str]] = []  # (source, key, default status)
    en = flatten(json.loads((FRONTEND / "messages" / "en.json").read_text(encoding="utf-8")))
    for key in sorted(en):
        status = "protocol-en" if key.startswith("chat.protocol.") else "machine-draft"
        rows.append(("messages/*.json", key, status))

    ts = (FRONTEND / "src" / "i18n" / "glossary.ts").read_text(encoding="utf-8")
    for table in GLOSSARY_TABLES:
        m = re.search(rf"export const {table}[^=]*=\s*\{{(.*?)\n\}};", ts, re.S)
        if not m:
            print(f"glossary table {table} not found", file=sys.stderr)
            return 1
        for k in re.findall(r'^\s{2}"?([^"\n:]+?)"?: \{', m.group(1), re.M):
            rows.append((f"src/i18n/glossary.ts::{table}", k, "machine-draft"))

    sys.path.insert(0, str(ROOT / "app" / "backend"))
    from app.i18n import en as backend_en  # noqa: E402

    for key in sorted(backend_en.STRINGS):
        rows.append(("app/backend/app/i18n/{am,om}.py", key, "machine-draft"))

    def status_for(lang: str, key: str, default: str) -> str:
        return "reviewed" if key in REVIEWED[lang] else default

    counts: dict[str, int] = {}
    lines = [
        "# Translation status — Amharic (am) and Afaan Oromoo (om)",
        "",
        f"Generated by `app/frontend/scripts/translation_status.py` on {date.today().isoformat()}.",
        "Every Amharic and Afaan Oromoo string in the product was **drafted by the",
        "implementation agent** and must be reviewed by a native speaker before release.",
        "To sign a row off, add its key to `REVIEWED` in the script and re-run it; the",
        "vitest parity test guarantees `am`/`om` carry every key `en` has.",
        "",
        "Statuses: `machine-draft` (needs native review) · `reviewed` (owner-approved) ·",
        "`protocol-en` (deliberately English in all languages: command strings the chat",
        "backend parses — `My challenge is …` — localising them is a U2 task that needs a",
        "language-aware intent parser).",
        "",
    ]
    table = ["| source | key | am | om |", "|---|---|---|---|"]
    for src, key, default in rows:
        am = status_for("am", key, default)
        om = status_for("om", key, default)
        for s in (am, om):
            counts[s] = counts.get(s, 0) + 1
        table.append(f"| `{src}` | `{key}` | {am} | {om} |")
    totals = " · ".join(f"{counts.get(s, 0)} {s}" for s in ("machine-draft", "reviewed", "protocol-en"))
    lines.append(f"**Totals (am + om cells):** {totals} — {len(rows)} keys.")
    lines.append("")
    lines.extend(table)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} keys; {totals}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
